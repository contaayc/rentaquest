export function extractLastTwoDigits(rawId: string): string {
  if (!rawId || !rawId.trim()) return '';
  
  // If formatted with hyphen like 123456789-5 or 80.123.456-1, strip the verification digit after hyphen
  let mainNumber = rawId.trim();
  if (mainNumber.includes('-')) {
    mainNumber = mainNumber.split('-')[0];
  }
  
  const clean = mainNumber.replace(/\D/g, '');
  if (!clean) return '';
  
  return clean.slice(-2).padStart(2, '0');
}

export function getDueDateByCedula(cedula: string): CalendarEntry {
  const last2DigitsStr = extractLastTwoDigits(cedula);
  if (!last2DigitsStr) {
    return DIAN_CALENDAR_2026[0];
  }
  
  const num = parseInt(last2DigitsStr, 10);
  const normalizedNum = num === 0 ? 100 : num;
  
  const match = DIAN_CALENDAR_2026.find(entry => {
    return normalizedNum >= entry.startDigit && normalizedNum <= entry.endDigit;
  });
  
  return match || DIAN_CALENDAR_2026[0];
}
